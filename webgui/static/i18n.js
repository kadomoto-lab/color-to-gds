let lang = 'en';
try { if (localStorage.getItem('color2gds-lang') === 'ja') lang = 'ja'; } catch {}
function t(key, ...args) {
  const value = MESSAGES[lang][key] ?? MESSAGES.en[key];
  return typeof value === 'function' ? value(...args) : value;
}
function localizeServerMessage(message) {
  if (lang !== 'ja') return message;
  for (const [pattern, replacement] of SERVER_MESSAGES_JA) if (pattern.test(message)) return message.replace(pattern, replacement);
  return message;
}
// Static markup: data-i18n sets the text, data-i18n-<attribute> sets that attribute.
function translatePage() {
  document.documentElement.lang = lang;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['aria-label', 'alt', 'title']) {
    for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
}
